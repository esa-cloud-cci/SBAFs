def get_coefficients(wmo_id, mode, avhrr_channel):
    """Return (slope, offset) for one source sensor/mode/AVHRR channel."""
    return SBAFS[(int(wmo_id), str(mode), str(avhrr_channel))]

def apply_sbaf(value, wmo_id, mode, avhrr_channel):
    """Transform source value(s) to the NOAA-18-AVHRR-equivalent value."""
    slope, offset = get_coefficients(wmo_id, mode, avhrr_channel)
    return value * slope + offset
