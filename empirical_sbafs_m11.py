# Current operational v10 application rules.
APPLICATION_RULES = {
    "visible": "day: SZA < 80 deg; SZA >= 80 deg is not used",
    "polar_3.8": "day: SZA < 75 deg; 75 <= SZA < 90 deg is not used; night: SZA >= 90 deg",
    "geo_3.8": "day: SZA < 90 deg; night: SZA > 90 deg",
    "11_12": "day: SZA < 80 deg; night: SZA >= 80 deg",
}

def get_coefficients(wmo_id, mode, channel):
    """Return (slope, offset) for one source sensor/mode/channel."""
    return SBAFS[(int(wmo_id), str(mode), str(channel))]

def apply_sbaf(value, wmo_id, mode, channel):
    """Transform source value(s) to the Meteosat-11-equivalent value."""
    slope, offset = get_coefficients(wmo_id, mode, channel)
    return value * slope + offset
